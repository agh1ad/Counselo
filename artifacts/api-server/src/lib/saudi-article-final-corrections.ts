function textOf(html: string): string {
  return html.replace(/<[^>]*>/g, "")
    .replace(/&#(?:x([0-9a-f]+)|(\d+));/gi, (entity, hex, decimal) => {
      const n = Number.parseInt(hex ?? decimal, hex ? 16 : 10);
      return n <= 0x10ffff ? String.fromCodePoint(n) : entity;
    })
    .replace(/&(nbsp|amp|quot|apos|lt|gt);/g, (entity, key: string) => ({nbsp:" ",amp:"&",quot:'"',apos:"'",lt:"<",gt:">"}[key] ?? entity))
    .replace(/\s+/g, " ").trim();
}

/** Exact reviewed passages only; unrelated prose, links, case facts and tags stay intact. */
export function correctSaudiArticleFinal(slug: string, lang: "en" | "ar", html: string): string {
  const changes = EXACT_ARTICLE_PASSAGES[`${lang}/${slug}`];
  if (!changes || !html) return html;
  return html.replace(/<(p|h2|h3)\b([^>]*)>([\s\S]*?)<\/\1>/gi, (original, tag, attrs, inner) => {
    const change = changes.find(item => item.from === textOf(inner));
    return change ? `<${tag}${attrs}>${change.to}</${tag}>` : original;
  });
}
